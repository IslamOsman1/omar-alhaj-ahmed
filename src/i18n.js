export function getLabel(item, lang, arabicKey, englishKey) {
  if (lang === 'en') {
    return item?.[englishKey] || item?.[arabicKey] || ''
  }

  return item?.[arabicKey] || item?.[englishKey] || ''
}

export function getMappedContent(section, id, lang, fallback) {
  if (lang !== 'en') return fallback
  return localizedContent[section]?.[id] || fallback
}
